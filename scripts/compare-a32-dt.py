#!/usr/bin/env python3
"""Compare typed DT properties and a symbolic k37 overlay view (no DTB emitted).

Overlay targets are resolved through __fixups__ and base __symbols__, not numeric
phandle equality. This report is analysis only, not libfdt overlay application.
"""
import argparse
import importlib.util
from pathlib import Path
import re
from a32_formats import fdt, strings, cells, sha

spec = importlib.util.spec_from_file_location('inventory', Path(__file__).with_name('a32-dt-inventory.py'))
inventory = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inventory)


def alias(path):
    path = path.replace('/pinctrl@0x10211000/mmc0@', '/pinctrl@0x10211000/msdc0@')
    path = path.replace('/pinctrl@0x10211000/mmc1@', '/pinctrl@0x10211000/msdc1@')
    return {'/memory@00000000': '/memory',
            '/mtk-msdc.0/msdc0@11230000': '/msdc@11230000',
            '/mtk-msdc.0/msdc1@11240000': '/msdc@11240000'}.get(path, path)


def canonical(tree, mapping=None, external=None):
    mapping, external = mapping or {}, external or {}
    result = {}
    for path, props in tree['nodes'].items():
        target = alias(mapping.get(path, path))
        if path.startswith('/__'):
            continue
        row = {}
        for key, data in props.items():
            if key in ('phandle', 'linux,phandle'):
                continue
            refs = inventory.references(key, data, tree)
            if refs and not any('UNKNOWN' in r or 'TRUNCATED' in r for r in refs):
                val = '; '.join(refs)
                # Longest path first prevents replacing a provider prefix twice.
                for old in sorted(mapping, key=len, reverse=True):
                    val = val.replace(old, mapping[old])
                val = alias(val)
                row[key] = 'REF ' + val
            else:
                row[key] = inventory.value(data)
            fixes = external.get((path, key))
            if fixes:
                # Preserve byte offset of each relocation; never substitute all 0xffffffff cells.
                row[key] = 'relocations ' + repr(fixes) + '; raw ' + inventory.value(data)
        result[target] = row
    return result


def overlay_view(base, overlay):
    symbols = base['nodes'].get('/__symbols__', {})
    fixups = overlay['nodes'].get('/__fixups__', {})
    targets, external = {}, {}
    for symbol, raw in fixups.items():
        if symbol not in symbols:
            raise ValueError(f'unresolved base symbol {symbol}')
        target = strings(symbols[symbol])[0]
        if target not in base['nodes']:
            raise ValueError('base symbol points to missing node')
        for fix in strings(raw):
            path, prop, offset = fix.rsplit(':', 2)
            offset = int(offset)
            data = overlay['nodes'][path][prop]
            if offset % 4 or offset + 4 > len(data):
                raise ValueError('invalid overlay relocation')
            if prop == 'target' and offset == 0:
                targets[path] = target
            else:
                external.setdefault((path, prop), []).append((offset, target))
    mapping = {}
    for path in overlay['nodes']:
        if path.startswith('/fragment@') and '/__overlay__' in path:
            fragment, suffix = path.split('/__overlay__', 1)
            if fragment not in targets:
                raise ValueError('unsupported overlay target')
            mapping[path] = targets[fragment].rstrip('/') + suffix
    view = canonical(base)
    converted = canonical(overlay, mapping, external)
    for old, new in mapping.items():
        view.setdefault(alias(new), {}).update(converted[alias(new)])
    return view, targets


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('stock', type=Path)
    p.add_argument('base', type=Path)
    p.add_argument('overlay', type=Path)
    p.add_argument('output', type=Path)
    args = p.parse_args()
    stock, base, overlay = [fdt(x.read_bytes()) for x in (args.stock, args.base, args.overlay)]
    views = [canonical(stock), canonical(base)]
    merged, targets = overlay_view(base, overlay)
    views.append(merged)
    lines = ['# A32 semantic DT property comparison', '',
             'Generated by `scripts/compare-a32-dt.py`. k37 column is a symbolic base +',
             'overlay view, not a bootable DTB or proof that LK applies that overlay.',
             'Stock memory and MSDC paths are explicitly aliased to equivalent 4.9 nodes.',
             'References resolve to paths; external relocations retain byte offsets.',
             'Register cell encodings remain raw; interpret through parent bus cells.',
             'ABSENT is not equivalent to disabled. Actions and driver implications are in',
             '[a32-stock-device-tree.md](a32-stock-device-tree.md).', '']
    for name, path in [('Stock', args.stock), ('Base', args.base), ('Overlay', args.overlay)]:
        lines += [f'{name}: SHA256 `{sha(path.read_bytes())}`.', '']
    lines += ['## Overlay target resolution', '', '| Fragment | Base node |', '|---|---|']
    lines += [f'| {k} | {v} |' for k, v in targets.items()]
    include = re.compile(r'^/$|chosen|^/memory$|reserved-memory|^/cpus|interrupt-controller@|/timer$|apxgpt|apuart|msdc@|toprgu|PWRAP|mt_pmic_regulator|keypad@|usb20@|MTKFB|/cap_touch@|/bat_|/aw3216$|/eta6195$|/SLEEP@|INFRACFG|PERICFG|/gpio$|/pinctrl@[^/]+$|/msdc[01]@')
    for path in sorted(set().union(*(set(v) for v in views))):
        if not include.search(path):
            continue
        rows = [v.get(path, {}) for v in views]
        keys = sorted(set().union(*(set(v) for v in rows)))
        lines += ['', f'## `{path}`', '', '| Property | Stock A32 | mt6735m 4.9 | k37 symbolic view |', '|---|---|---|---|']
        for key in keys:
            vals = [r.get(key, 'ABSENT') for r in rows]
            vals = [x.replace('|', '\\|').replace('\n', ' ') for x in vals]
            lines += [f'| {key} | ' + ' | '.join('`' + x + '`' for x in vals) + ' |']
    args.output.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
